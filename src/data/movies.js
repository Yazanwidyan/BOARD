const seededRating = (rank, seed) => {
  const base = 9.4 - (rank / RAW_MOVIES.length) * 2.2;
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  const jitter = (hash % 40) / 100 - 0.2;
  const rating = Math.max(7.0, Math.min(9.5, base + jitter));
  return Math.round(rating * 10) / 10;
};

export const MOVIES = RAW_MOVIES.map(
  ([title, year, runtime, director, genres, description, franchise], index) => {
    const rank = index + 1;
    const id = `m${rank}`;
    return {
      id,
      rank,
      title,
      year,
      rating: seededRating(rank, title),
      runtime,
      genres,
      director,
      description,
      franchise: franchise ?? null,
      poster: buildPoster(index),
      backdrop: buildBackdrop(id),
    };
  },
);

export const getMovieById = (id) => MOVIES.find((movie) => movie.id === id);

export default MOVIES;
